"""
Exercício 4 - Dobro, triplo e metade

Leia um número real e mostre o dobro, o triplo e a metade desse
valor.
"""

valor = float(input("Digite um valor: "))

dobro = valor * 2
triplo = valor * 3
metade = valor / 2

print()
print(f"Dobro: {dobro}")
print(f"Triplo: {triplo}")
print(f"Metade: {metade}")
