"""
Exercício 7 - Celsius para Fahrenheit

Leia uma temperatura em graus Celsius e mostre o valor equivalente
em Fahrenheit.

Regra: Fahrenheit = Celsius x 9 / 5 + 32.
"""

celsius = float(input("Temperatura em °C: "))

fahrenheit = celsius * 9 / 5 + 32

print()
print(f"Temperatura em °F: {fahrenheit}")
