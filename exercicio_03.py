"""
Exercício 3 - Antecessor e sucessor

Leia um número inteiro e mostre o seu antecessor e o seu sucessor.
"""

numero = int(input("Digite um número: "))

antecessor = numero - 1
sucessor = numero + 1

print()
print(f"Antecessor: {antecessor}")
print(f"Número: {numero}")
print(f"Sucessor: {sucessor}")
